"""Measure the guardrail rules on held-out replies (owner: Juee).

    python evals/guardrail_eval.py            # print the results
    python evals/guardrail_eval.py --write    # also update docs/guardrail_eval.md

The replies in evals/guardrail_replies.json were written separately from the unit tests. Round 1 was measured
before the rules had seen them; the rules were then widened using its misses (see "history" in the JSON).
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.guardrails import explain  # noqa: E402

REASONS = ["exploitation_concern", "advice_request", "out_of_scope", "1099r_taxable_not_determined", "uncertain"]


def evaluate(cases):
    rows = []
    for case in cases:
        got = explain(case["reply"])
        rows.append({**case, "got": got.reason, "rule": got.rule})
    return rows


def report(rows, history=()) -> str:
    tp, fp, fn = Counter(), Counter(), Counter()
    for r in rows:
        if r["got"] == r["expected"]:
            if r["expected"]:
                tp[r["expected"]] += 1
            continue
        if r["got"]:
            fp[r["got"]] += 1
        if r["expected"]:
            fn[r["expected"]] += 1

    def pct(a, b):
        return f"{100 * a / b:.0f}%" if b else "n/a"

    correct = sum(r["got"] == r["expected"] for r in rows)
    ordinary = [r for r in rows if r["expected"] is None]
    false_alarms = sum(1 for r in ordinary if r["got"])
    lines = [
        "# Guardrail evaluation",
        "",
        "Generated by `python evals/guardrail_eval.py --write` from `evals/guardrail_replies.json`. These replies",
        "were written separately from the unit tests.",
        "",
        *(["## History", "", *[f"- {h}" for h in history], "", "## Current rules", ""] if history else []),
        f"**{correct} of {len(rows)} replies classified correctly ({pct(correct, len(rows))}).** "
        f"Ordinary answers wrongly escalated: {false_alarms} of {len(ordinary)}.",
        "",
        "| Reason | Expected | Caught | Recall | False alarms | Precision |",
        "|---|---|---|---|---|---|",
    ]
    for reason in REASONS:
        expected = tp[reason] + fn[reason]
        lines.append(f"| `{reason}` | {expected} | {tp[reason]} | {pct(tp[reason], expected)} | {fp[reason]} | "
                     f"{pct(tp[reason], tp[reason] + fp[reason])} |")
    misses = [r for r in rows if r["got"] != r["expected"]]
    lines += ["", "## Misclassified replies", ""]
    if misses:
        lines += ["| Reply | Expected | Got (rule) |", "|---|---|---|"]
        for r in misses:
            got = f"`{r['got']}` ({r['rule']})" if r["got"] else "none"
            lines.append(f"| {r['reply']} | `{r['expected']}` | {got} |")
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="update docs/guardrail_eval.md")
    args = parser.parse_args()
    data = json.loads((ROOT / "evals/guardrail_replies.json").read_text())
    text = report(evaluate(data["cases"]), data.get("history", []))
    print(text)
    if args.write:
        (ROOT / "docs/guardrail_eval.md").write_text(text)


if __name__ == "__main__":
    main()
